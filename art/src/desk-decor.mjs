/** Todos os sprites com a tag `'desk-decor'` unificados. */
export const ALL_DESK_DECOR_SPRITES = [
  ...DESK_SURFACES,
  ...DESK_COMPUTER_SETUPS,
  ...DESK_DECOR_ITEMS,
];

/** Filtra ativos de decoração de mesa por tag (ex.: `'desk-decor'`, `'desk-item'`, `'desk-setup'`). */
export const getDeskDecorByTag = (tag = DESK_DECOR_TAG) =>
  ALL_DESK_DECOR_SPRITES.filter((s) => s.tags.includes(tag));

/**
 * Compila uma mesa completa personalizada (Tampo + Setup Central + até 4 Itens nos Cantos)
 * devolvendo a lista unificada de `<rect>` em coordenadas de mapa (96 x 36 px).
 */
export const composeCustomDeskRects = ({
  surfaceId = 'desk_surface_white_tech',
  setupId = 'setup_dual_monitor',
  itemIds = ['item_plant', 'item_lamp', 'item_mug', 'item_duck'],
  scale = PIXEL_SCALE,
}) => {
  const surface =
    DESK_SURFACES.find((s) => s.id === surfaceId) ?? DESK_SURFACES[0];
  const setup =
    DESK_COMPUTER_SETUPS.find((s) => s.id === setupId) ??
    DESK_COMPUTER_SETUPS[0];

  validateSprite(surface);
  validateSprite(setup);

  const rects = [...compileSprite(surface, scale)];

  // Centraliza o setup de computador (28x14 art px) no meio da bancada (48x18 art px)
  const setupOffsetX = 10 * scale;
  const setupOffsetY = -3 * scale;
  for (const r of compileSprite(setup, scale)) {
    rects.push({
      ...r,
      x: r.x + setupOffsetX,
      y: r.y + setupOffsetY,
    });
  }

  // 4 Slots de decoração nos cantos do tampo (Trás-Esq, Trás-Dir, Frente-Dir, Frente-Esq)
  const SLOTS_ART = [
    { x: 1, y: -2 }, // Slot 0: Canto superior esquerdo
    { x: 37, y: -2 }, // Slot 1: Canto superior direito
    { x: 37, y: 3 }, // Slot 2: Canto inferior direito
    { x: 1, y: 3 }, // Slot 3: Canto inferior esquerdo
  ];

  itemIds.slice(0, 4).forEach((itemId, index) => {
    if (!itemId || itemId === 'none') return;
    const item = DESK_DECOR_ITEMS.find(
      (i) => i.id === itemId || i.itemKey === itemId,
    );
    if (!item) return;
    validateSprite(item);
    const slot = SLOTS_ART[index];
    for (const r of compileSprite(item, scale)) {
      rects.push({
        ...r,
        x: r.x + slot.x * scale,
        y: r.y + slot.y * scale,
      });
    }
  });

  return rects;
};
